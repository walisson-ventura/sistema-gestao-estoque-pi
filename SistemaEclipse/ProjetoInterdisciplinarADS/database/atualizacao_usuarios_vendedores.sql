-- 1) Usuários vendedores. O administrador legado continua autenticando
--    por admin/123 no LoginController; vendedores são persistidos aqui.
CREATE TABLE tb_usuario (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nome        VARCHAR2(150 CHAR) NOT NULL,
    cpf         VARCHAR2(11 CHAR) NOT NULL,
    telefone    VARCHAR2(20 CHAR) NOT NULL,
    senha_hash  VARCHAR2(500 CHAR) NOT NULL,
    perfil      VARCHAR2(20 CHAR) DEFAULT 'VENDEDOR' NOT NULL,
    ativo       CHAR(1 CHAR) DEFAULT 'S' NOT NULL,
    criado_em   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_tb_usuario PRIMARY KEY (id),
    CONSTRAINT uq_tb_usuario_cpf UNIQUE (cpf),
    CONSTRAINT ck_tb_usuario_perfil CHECK (perfil IN ('ADMIN','VENDEDOR')),
    CONSTRAINT ck_tb_usuario_ativo CHECK (ativo IN ('S','N'))
);

-- 2) Adiciona a referência ao vendedor responsável por cada venda.
--    NULL é permitido para vendas antigas e vendas feitas pelo admin.
ALTER TABLE tb_venda ADD (vendedor_id NUMBER NULL);

ALTER TABLE tb_venda ADD CONSTRAINT fk_venda_vendedor
    FOREIGN KEY (vendedor_id) REFERENCES tb_usuario(id);

CREATE INDEX ix_tb_venda_vendedor_data ON tb_venda (vendedor_id, data_venda);

-- 3) Índice para consulta de clientes por CPF. Antes de ativar a restrição
--    UNIQUE, confira e normalize os CPFs antigos de tb_cliente.cpf_cnpj.
CREATE INDEX ix_tb_cliente_cpf ON tb_cliente (cpf_cnpj);

